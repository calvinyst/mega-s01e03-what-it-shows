import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { deskRef } from '../src/lib/kb/desk-ref.ts';
const report = JSON.parse(await readFile('evidence/analysis.json','utf8'));
assert.equal(report.rawRows,427);
assert.equal(report.uniqueIds,412);
assert.equal(report.duplicateRows,15);
assert.equal(report.merged,412);
assert.deepEqual(report.groups.map(g=>[g.cause,g.reports.length]),[['parser',379],['hint',33]]);
assert.equal(new Set(report.groups.flatMap(g=>g.reports)).size,412);
assert.equal(report.tagDisagreements.length,38);
const source = await readFile('src/routes/kb/decisions/0002-dedupe-by-cause/+page.svx','utf8');
const signature = source.match(/^signature: '(.*)'$/m)?.[1];
assert.ok(signature);
assert.ok(source.trimEnd().endsWith('<RenderStamp {signature} />'));
const html = await readFile('rendered/kb/decisions/0002-dedupe-by-cause/index.html','utf8');
assert.ok(html.includes(deskRef(signature)));
for (const expected of ['379','33','412','427','183','different causes — keep apart','R-41202','R-41620']) assert.ok(html.includes(expected),expected);
assert.ok(!html.includes('no desk ref:'));
console.log('Verified: complete, disjoint report groups; duplicate accounting; intake mismatch count; rendered counts, anomalies, controls and generated desk reference.');
